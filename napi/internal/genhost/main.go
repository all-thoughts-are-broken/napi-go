// Command genhost writes napi/host_symbols.h: the list of every Node-API
// function declared by the vendored headers at NAPI_VERSION 8, in a form the C
// preprocessor can expand into definitions (see host_windows.c).
//
// Run it through go generate, from the napi package:
//
//	go generate ./napi
//
// It asks the C preprocessor for the declarations rather than parsing the
// headers itself, so the #if NAPI_VERSION / NAPI_EXPERIMENTAL conditions are
// evaluated by the tool that owns them. The compiler is $CC, or gcc/cc.
package main

import (
	"bytes"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"runtime"
	"strings"
)

const (
	includeDir = "../include/node"
	output     = "host_symbols.h"
	// napiVersion is the Node-API version this module binds. Functions the
	// headers only declare above it are left out on purpose.
	napiVersion = "8"
)

// declaration matches one preprocessed function prototype, for example
//
//	napi_status napi_get_boolean(napi_env env, bool value, napi_value* result)
//	__attribute__((noreturn)) void napi_fatal_error(const char* location, ...)
var declaration = regexp.MustCompile(
	`^(__attribute__\(\(noreturn\)\) )?(napi_status|void) ((?:napi|node_api)_[a-z0-9_]+) ?\((.*)\)$`)

var identifier = regexp.MustCompile(`[A-Za-z_][A-Za-z0-9_]*$`)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "genhost:", err)
		os.Exit(1)
	}
}

func run() error {
	cc := os.Getenv("CC")
	if cc == "" {
		cc = "cc"
		if runtime.GOOS == "windows" {
			cc = "gcc"
		}
	}
	// NAPI_EXTERN and NAPI_CDECL are emptied so the prototypes come out the
	// same on every platform; host_windows.c puts the calling convention back.
	args := append(strings.Fields(cc)[1:],
		"-E", "-P",
		"-DNAPI_VERSION="+napiVersion, "-DNAPI_EXTERN=", "-DNAPI_CDECL=",
		"-I"+includeDir, filepath.Join(includeDir, "node_api.h"))
	cmd := exec.Command(strings.Fields(cc)[0], args...)
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	preprocessed, err := cmd.Output()
	if err != nil {
		return fmt.Errorf("%s: %v\n%s", cc, err, stderr.String())
	}

	var out bytes.Buffer
	out.WriteString(header)
	count := 0
	for _, statement := range strings.Split(string(preprocessed), ";") {
		statement = strings.Join(strings.Fields(statement), " ")
		m := declaration.FindStringSubmatch(statement)
		if m == nil {
			continue
		}
		noreturn, returns, name, params := m[1] != "", m[2], m[3], strings.TrimSpace(m[4])

		macro := "NAPI_GO_HOST"
		switch {
		case noreturn:
			macro = "NAPI_GO_HOST_NORETURN"
		case returns == "void":
			macro = "NAPI_GO_HOST_VOID"
		}

		var names []string
		if params != "void" && params != "" {
			for _, p := range strings.Split(params, ",") {
				id := identifier.FindString(strings.TrimSpace(p))
				if id == "" {
					return fmt.Errorf("%s: parameter %q has no name", name, p)
				}
				names = append(names, id)
			}
		} else {
			params = "void"
		}
		fmt.Fprintf(&out, "%s(%s, (%s), (%s))\n", macro, name, params, strings.Join(names, ", "))
		count++
	}
	if count == 0 {
		return fmt.Errorf("no Node-API declarations found in the output of %s", cc)
	}
	return os.WriteFile(output, out.Bytes(), 0o644)
}

const header = `// Code generated by go generate (napi/internal/genhost); DO NOT EDIT.
//
// Every Node-API function the vendored headers declare at NAPI_VERSION ` + napiVersion + `,
// one per line, for the including file to expand:
//
//   NAPI_GO_HOST(name, (parameters), (arguments))           returns napi_status
//   NAPI_GO_HOST_VOID(name, (parameters), (arguments))      returns nothing
//   NAPI_GO_HOST_NORETURN(name, (parameters), (arguments))  does not return
//
// host_windows.c includes it twice: once to define each function as a jump
// through a pointer, once to build the table that fills those pointers in.

`
